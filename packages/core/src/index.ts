export function resolveFrontoProps<T extends keyof FrontoTypeMap>(
    type: T,
    provided?: Partial<FrontoComponentProps<FrontoTypeMap[T]>>,
): FrontoComponentProps<FrontoTypeMap[T]> {
    const typeDefaults = FRONTO_TYPE_DEFAULTS[type] || {}
    return {
        ...FRONTO_DEFAULT_PROPS,
        ...typeDefaults,
        ...provided,
    } as FrontoComponentProps<FrontoTypeMap[T]>
}


export function normalizeDatetimeToUtcIso(
    value: string | Date | null | undefined,
): string | null | undefined {
    if (value === undefined || value === null) {
        return value
    }

    const parsedDate = value instanceof Date ? value : new Date(value)
    if (Number.isNaN(parsedDate.getTime())) {
        throw new Error(`Invalid datetime value: ${String(value)}`)
    }

    return parsedDate.toISOString()
}

export function isBase64(value: string): boolean {
    if (value.length === 0) {
        return true
    }
    if (value.length % 4 !== 0) {
        return false
    }
    return /^[A-Za-z0-9+/]*={0,2}$/.test(value)
}

export function isValueInEnum<T extends keyof FrontoTypeMap>(
    value: FrontoTypeMap[T],
    enumValues: FrontoTypeMap[T][] | undefined,
): boolean {
    console.log('[CORE] isValueInEnum called with value:', value, 'and enumValues:', enumValues)
    if (enumValues === undefined) {
        return true
    }
    if (enumValues?.length === 0) {
        return false
    }
    return enumValues.some((enumValue) => {
        if (value instanceof Date && enumValue instanceof Date) {
            return value.getTime() === enumValue.getTime()
        }
        return value === enumValue
    })
}

