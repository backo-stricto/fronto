export type ComponentRegistry = Record<string, Record<string, string>>

type FrontoTypeMap = {
    Bool: boolean | null
    Int: number | null
    Float: number | null
    String: string | null
    Datetime: Date | null
    Bytes: Uint8Array | null
    Dict: Record<string, unknown> | null
}

export interface FrontoComponentProps<TValue = unknown> {
    exist: boolean,
    readable: boolean,
    writable: boolean,
    required: boolean,
    description: string,
    errorMessage: string,
    defaultValue: TValue | null,
    value: TValue | null,
    enum: TValue[] | undefined,
    onChange?: (value: TValue) => void,
}

export type FrontoProps<T extends keyof FrontoTypeMap> = FrontoComponentProps<FrontoTypeMap[T]>

export const FRONTO_DEFAULT_PROPS = {
    exist: true,
    readable: true,
    writable: true,
    required: false,
    description: '',
    errorMessage: '',
    defaultValue: undefined,
    value: undefined,
    enum: undefined,
    onChange: undefined,
} satisfies FrontoComponentProps<unknown>

